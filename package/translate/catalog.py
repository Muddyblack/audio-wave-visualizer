"""Writes the studio's Turkish catalog as a JavaScript module, from tr.po.

Usage: catalog.py TR_PO OUTPUT.js
"""

import json
import re
import sys
from pathlib import Path


def unescape(text):
    return re.sub(
        r"\\(.)", lambda m: {"n": "\n", "t": "\t"}.get(m.group(1), m.group(1)), text
    )


def read_entries(path):
    entries = {}
    msgid = msgstr = field = None

    def flush():
        if msgid and msgstr:
            entries[msgid] = msgstr

    for line in Path(path).read_text(encoding="utf-8").split("\n"):
        if line.startswith("msgid "):
            flush()
            msgid, msgstr, field = unescape(line[7:-1]), None, "id"
        elif line.startswith("msgstr "):
            msgstr, field = unescape(line[8:-1]), "str"
        elif line.startswith('"') and field == "id":
            msgid += unescape(line[1:-1])
        elif line.startswith('"') and field == "str":
            msgstr += unescape(line[1:-1])
        elif not line.strip():
            flush()
            msgid = field = None
    flush()
    entries.pop("", None)
    return entries


def render(entries):
    body = json.dumps(dict(sorted(entries.items())), ensure_ascii=False, indent=1)
    return (
        ".pragma library\n"
        "// Generated by package/translate/Messages.sh from tr.po. Do not edit.\n\n"
        f"var messages = {body};\n"
    )


if __name__ == "__main__":
    Path(sys.argv[2]).write_text(render(read_entries(sys.argv[1])), encoding="utf-8")
